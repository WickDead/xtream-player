import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const base = process.argv[2] || "/";
if (!/^\/(?:[A-Za-z0-9_.-]+\/)*$/.test(base)) throw new Error("Base must be an absolute directory path ending in /.");
execFileSync("dotnet", ["publish", "src/XtreamPlayer.Web", "-c", "Release", "-o", "dist/pwa", "--nologo"], { cwd: root, stdio: "inherit" });
const output = resolve(root, "dist/pwa/wwwroot");
const index = readFileSync(resolve(output, "index.html"), "utf8").replace('<base href="/" />', `<base href="${base}" />`);
writeFileSync(resolve(output, "index.html"), index);
const path = resolve(output, "service-worker-assets.js");
const source = readFileSync(path, "utf8");
const start = source.indexOf("{"), end = source.lastIndexOf("}");
const manifest = JSON.parse(source.slice(start, end + 1));
const hash = "sha256-" + createHash("sha256").update(index).digest("base64");
const asset = manifest.assets.find(a => a.url === "index.html");
if (!asset) throw new Error("The service worker manifest did not include index.html.");
asset.hash = hash;
manifest.version = createHash("sha256").update(JSON.stringify(manifest.assets)).digest("hex").slice(0, 16);
writeFileSync(path, "self.assetsManifest = " + JSON.stringify(manifest, null, 2) + ";\n");
writeFileSync(resolve(output, ".nojekyll"), "");
console.log("PWA ready at " + output + " (base " + base + ")");
